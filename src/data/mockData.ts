export interface AvatarHeadAnchor {
  /** Horizontal center of the head crown in % (0-100) of the square container */
  centerX: number;
  /** Vertical position of the head crown in % (0-100) of the square container */
  crownY: number;
  /** Width of the head across the ears/temples in % (0-100) of the square container */
  headWidth: number;
  /** Natural tilt of the avatar's head in degrees (negative = tilted left, positive = tilted right) */
  tiltDeg: number;
}

export interface AccessoryFitProfile {
  /** Native width-to-height ratio of the cropped accessory PNG */
  aspectRatio: number;
  /** Width of the accessory relative to the avatar's headWidth */
  widthMultiplier: number;
  /** Fraction (0..1) from the top of the accessory image that sits on the avatar's crownY */
  contactY: number;
  /** Horizontal shift relative to avatar headWidth */
  offsetX: number;
  /** Additional stylistic tilt in degrees added to the avatar's head tilt */
  tiltOffsetDeg: number;
}

